import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect, type Locator, type Page, test } from "@playwright/test";
import { cutsFromMarks, type Mark } from "../scripts/make-demo.js";
import { exampleLabel, reviewHash } from "../src/web/logic.js";

/**
 * The README's images and demo, from the real agent (slice 0016). Run by
 * `npm run screenshots` with `playwright.capture.config.ts`, against an app the
 * person started on the local model; skipped everywhere else, so
 * `npm run test:e2e` lists it as skipped and checks nothing here.
 *
 * The model's words aren't reproducible, so nothing here asserts them. The
 * images are looked at and committed as captured, never regenerated by a test.
 * Every answer typed is made up, from `ANSWERS` below.
 */
test.skip(process.env.CAPTURE !== "1", "run with npm run screenshots");
test.describe.configure({ mode: "serial" });

/** A short oncology trial from 0013's gate: it parsed cleanly there in about 30 seconds. */
const ADDED = "NCT05854498";
/** The live screening: a built-in example with hand labels. */
const SCREENED = "NCT04316364";
/** The committed conversation the review images show, as before (README: turn 6). */
const EXAMPLE = "eval NCT00077350-v2-labels";
const OUT = "docs/images";
const WORK = "e2e/.out/capture";
const PARSE_TIMEOUT = 300_000;
const REPLY_TIMEOUT = 120_000;

/**
 * One made-up person's answers (spec §2.3), by what the agent's latest
 * question mentions. The first match wins. Written before any run, and not
 * tuned to one.
 */
const ANSWERS: [RegExp, string][] = [
  [
    /biopsy|confirm|diagnos|stage/i,
    "Yes, a biopsy last spring confirmed stage II non-small cell lung cancer.",
  ],
  [/surg|resect/i, "My surgeon said it can be removed, and I'm scheduled to meet them next month."],
  [/ECOG|daily activit|performance/i, "I'm up and about all day and still working part time."],
  [/chemo|radiation|treatment/i, "No, I haven't had any treatment for it yet."],
  [/pregnan/i, "No."],
];
const FALLBACK = "I'm not sure, I'd have to check.";

function answerFor(question: string): string {
  return ANSWERS.find(([pattern]) => pattern.test(question))?.[1] ?? FALLBACK;
}

function trialCard(page: Page, nctId: string): Locator {
  return page.locator("article.trial-card").filter({ hasText: nctId });
}

function agentBubbles(page: Page): Locator {
  return page.locator(".bubble.from-agent:not(.waiting)");
}

/**
 * Stops unless the page is on the local model: fake mode can't make these
 * images, and a hosted model chosen in a person's own Settings would spend
 * money and could show their key (slice 0017).
 */
async function requireRealModel(page: Page): Promise<void> {
  await page.goto("/");
  await expect(
    page.locator(".pill"),
    "Start the app on the local model: npm run app -- --examples --port 5035 --chats-dir <tmp>/chats --trials-dir <tmp>/trials --settings-dir <tmp>/settings",
  ).toContainText("Local model");
}

/** Removes an added trial, as `e2e/trials.spec.ts` does, if it's there. */
async function removeIfPresent(page: Page, nctId: string): Promise<void> {
  await page.goto("/");
  const card = trialCard(page, nctId);
  if ((await card.count()) > 0) {
    await card.getByRole("button", { name: "Remove…" }).click();
    await card.getByRole("button", { name: "Remove", exact: true }).click();
  }
  await expect(card).toHaveCount(0);
}

/** Waits until the agent has said something new and nothing is pending. */
async function agentAnswered(page: Page, before: number): Promise<void> {
  await expect
    .poll(() => agentBubbles(page).count(), { timeout: REPLY_TIMEOUT })
    .toBeGreaterThan(before);
  await expect(page.locator(".bubble.waiting")).toHaveCount(0, { timeout: REPLY_TIMEOUT });
}

/**
 * The agent's latest question: the last paragraph of its latest message. The
 * first message opens with a greeting naming the trial, and a title like
 * "…Resectable NSCLC" mustn't choose the answer (found on the first run).
 */
async function lastQuestion(page: Page): Promise<string> {
  const text = await agentBubbles(page).last().innerText();
  return (
    text
      .trim()
      .split(/\n\s*\n/)
      .pop() ?? text
  );
}

/** Answers the latest question from `ANSWERS`, typing at `delay` ms a key. */
async function reply(page: Page, delay = 0): Promise<{ question: string; answer: string }> {
  const question = await lastQuestion(page);
  const answer = answerFor(question);
  const before = await agentBubbles(page).count();
  const box = page.getByRole("textbox");
  if (delay > 0) {
    await box.pressSequentially(answer, { delay });
  } else {
    await box.fill(answer);
  }
  await box.press("Enter");
  await agentAnswered(page, before);
  return { question, answer };
}

async function startScreening(page: Page): Promise<void> {
  await page.goto("/#/screenings");
  await page
    .locator("li.study-card")
    .filter({ hasText: SCREENED })
    .getByRole("button", { name: "Start" })
    .click();
  await agentAnswered(page, 0);
}

async function openExample(page: Page): Promise<void> {
  await page.goto("/#/reviews");
  await page.locator(`a[href="${reviewHash(EXAMPLE)}"]`).click();
  await expect(
    page.locator(".review-head").getByText(exampleLabel(EXAMPLE), { exact: true }),
  ).toBeVisible();
}

/**
 * A caption over the page while the demo records: test code, not the page's.
 * It goes in through the body's handle, since this tsconfig has no DOM types.
 */
async function caption(page: Page, text: string): Promise<void> {
  await page.locator("body").evaluate((body, words) => {
    const el = body.ownerDocument.createElement("div");
    el.id = "capture-caption";
    el.textContent = words;
    el.setAttribute(
      "style",
      "position:fixed;left:50%;bottom:28px;transform:translateX(-50%);z-index:9999;" +
        "padding:10px 18px;border-radius:999px;background:rgba(0,0,0,.8);color:#fff;" +
        "font:500 16px/1.3 system-ui,-apple-system,sans-serif",
    );
    body.append(el);
  }, text);
}

async function clearCaption(page: Page): Promise<void> {
  await page.locator("#capture-caption").evaluate((el) => el.remove());
}

test("stills: Trials, a screening, the review and its conversation", async ({ page }) => {
  await requireRealModel(page);
  await removeIfPresent(page, ADDED);
  mkdirSync(WORK, { recursive: true });

  await page
    .getByRole("textbox", { name: "ClinicalTrials.gov link or NCT ID" })
    .fill(`https://clinicaltrials.gov/study/${ADDED}`);
  await page.getByRole("button", { name: "Add trial" }).click();
  await expect(trialCard(page, ADDED)).toContainText("Ready ·", { timeout: PARSE_TIMEOUT });
  await page.locator("header").first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${OUT}/trials.png` });

  await startScreening(page);
  await page.getByRole("button", { name: /^Show the \d+ rules$/ }).click();
  const exchanges = [];
  for (let i = 0; i < 3; i++) {
    exchanges.push(await reply(page));
  }
  // The model's words, for the plan's Records. Made-up answers only.
  writeFileSync(`${WORK}/screening.json`, `${JSON.stringify(exchanges, null, 2)}\n`);
  await page.screenshot({ path: `${OUT}/screening.png` });

  await openExample(page);
  await page.screenshot({ path: `${OUT}/review.png` });
  const heading = page.getByRole("heading", { name: "The conversation", exact: true });
  await heading.evaluate((el) => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: `${OUT}/transcript.png` });

  await removeIfPresent(page, ADDED);
});

test("demo: add a trial, its checklist, two answers, the review", async ({ browser, page }) => {
  await requireRealModel(page);
  await removeIfPresent(page, ADDED);
  mkdirSync(WORK, { recursive: true });

  const size = { width: 1280, height: 800 };
  const context = await browser.newContext({
    baseURL: test.info().project.use.baseURL ?? "",
    viewport: size,
    deviceScaleFactor: 1,
    colorScheme: "light",
    recordVideo: { dir: `${WORK}/video`, size },
  });
  const demo = await context.newPage();
  const t0 = Date.now();
  const marks: Mark[] = [];
  const now = () => (Date.now() - t0) / 1000;
  const hold = (ms: number) => demo.waitForTimeout(ms);

  // A wait on the model: captioned, and sped up by `npm run demo`.
  const waitFor = async (text: string, done: () => Promise<void>) => {
    await caption(demo, text);
    marks.push({ at: now(), label: "wait-start" });
    await done();
    marks.push({ at: now(), label: "wait-end" });
    await clearCaption(demo);
  };

  await demo.goto("/");
  await hold(1200);
  await demo
    .getByRole("textbox", { name: "ClinicalTrials.gov link or NCT ID" })
    .pressSequentially(`https://clinicaltrials.gov/study/${ADDED}`, { delay: 25 });
  await demo.getByRole("button", { name: "Add trial" }).click();
  await waitFor("The local model is reading the trial's rules (shortened)", () =>
    expect(trialCard(demo, ADDED)).toContainText("Ready ·", { timeout: PARSE_TIMEOUT }),
  );
  await hold(1500);

  // What the AI read from the added trial. The screening that follows is on the
  // built-in lung trial: `ANSWERS` are one made-up lung cancer patient's, and
  // the added trial is for colorectal cancer (changed after the first run).
  await trialCard(demo, ADDED).getByRole("link", { name: "See the checklist" }).click();
  await hold(2500);
  await demo.getByRole("link", { name: "Screenings" }).click();
  await caption(demo, "A screening on one of the built-in lung cancer trials");
  await hold(1500);
  await clearCaption(demo);
  await demo
    .locator("li.study-card")
    .filter({ hasText: SCREENED })
    .getByRole("button", { name: "Start" })
    .click();
  await waitFor("The AI is writing its first question (shortened)", () => agentAnswered(demo, 0));
  await hold(2500);
  for (let i = 0; i < 2; i++) {
    const question = await lastQuestion(demo);
    const before = await agentBubbles(demo).count();
    const box = demo.getByRole("textbox");
    await box.pressSequentially(answerFor(question), { delay: 25 });
    await box.press("Enter");
    await waitFor("Thinking (shortened)", () => agentAnswered(demo, before));
    await hold(2500);
  }

  await openExample(demo);
  await caption(demo, "A finished screening, from the project's examples");
  await hold(2500);
  await clearCaption(demo);
  for (let i = 0; i < 6; i++) {
    await demo.mouse.wheel(0, 90);
    await hold(120);
  }
  await hold(800);
  await demo.locator(".review-row summary").first().click();
  await hold(2000);

  const end = now();
  const video = demo.video();
  await context.close();
  const path = await video?.path();
  writeFileSync(
    `${WORK}/cuts.json`,
    `${JSON.stringify({ video: path, cuts: cutsFromMarks(marks, end) }, null, 2)}\n`,
  );

  await removeIfPresent(page, ADDED);
});

